'use client';

import { getImageProps } from 'next/image';
import { useEffect, useRef, useState } from 'react';
import { useActiveOnScreen, useReducedMotion, useSaveData } from '@/lib/usePlaybackConditions';

/**
 * Hero media: an illustrative farmhouse scale model on architectural drawings.
 * - Stills are art-directed (portrait on phones, wide from 768px) and render immediately.
 * - One clip loads (the one matching the screen), only when on screen, never with reduced motion,
 *   and not automatically under Data Saver.
 * - The clips are slow push-ins whose ends don't match, so they play ONCE and hold the last frame.
 * Media is generated by scripts/prepare-hero-media.sh.
 */
const WIDE = { src: '/media/hero/hero-home-wide.webp', width: 2400, height: 1340, video: '/media/hero/hero-home-wide.mp4' };
const TALL = { src: '/media/hero/hero-home-tall.webp', width: 720, height: 1280, video: '/media/hero/hero-home-tall.mp4' };
const ALT =
  'Illustrative scale model of a white two-story farmhouse with a dark metal roof, cedar gables, a covered porch with rocking chairs and an orange front door, a flowering dogwood and two pines, sitting on architectural drawings in warm afternoon light';

// Same crop for the still and the video so the crossfade lines up.
const FIT = 'object-cover object-[50%_88%] md:object-center';

type Playback = 'idle' | 'playing' | 'paused' | 'ended';

export default function HeroMedia() {
  const boxRef = useRef<HTMLDivElement>(null);
  const videoRef = useRef<HTMLVideoElement>(null);
  const reduced = useReducedMotion();
  const saveData = useSaveData();
  const active = useActiveOnScreen(boxRef);
  const [manualStart, setManualStart] = useState(false);
  const [userPaused, setUserPaused] = useState(false);
  const [playback, setPlayback] = useState<Playback>('idle');
  const [frames, setFrames] = useState(false);
  const [failed, setFailed] = useState(false);

  const allowed = !reduced && !failed;
  const started = allowed && (manualStart || !saveData);

  // Attach the right clip lazily, play while on screen, pause when offscreen or hidden.
  useEffect(() => {
    const v = videoRef.current;
    if (!v) return;
    if (started && active && !userPaused && !v.ended) {
      if (!v.getAttribute('src')) v.src = window.matchMedia('(min-width: 768px)').matches ? WIDE.video : TALL.video;
      v.play().catch((err: DOMException) => {
        if (err?.name === 'NotAllowedError') setUserPaused(true); // autoplay refused: keep the still
      });
    } else if (v.getAttribute('src') && !v.paused) {
      v.pause();
    }
  }, [started, active, userPaused]);

  const control = () => {
    const v = videoRef.current;
    if (!started) {
      setManualStart(true);
      setUserPaused(false);
    } else if (playback === 'ended' && v) {
      v.currentTime = 0;
      setUserPaused(false);
      v.play().catch(() => {});
    } else {
      setUserPaused((p) => !p);
    }
  };

  const common = { alt: ALT, sizes: '(min-width: 1024px) 78vw, 100vw', priority: true } as const;
  const { props: wideProps } = getImageProps({ ...common, src: WIDE.src, width: WIDE.width, height: WIDE.height, quality: 82 });
  const {
    props: { srcSet: tallSrcSet, ...tallProps },
  } = getImageProps({ ...common, src: TALL.src, width: TALL.width, height: TALL.height, quality: 85 });

  const label = !started ? 'Play animation' : playback === 'ended' ? 'Replay animation' : playback === 'playing' ? 'Pause animation' : 'Play animation';

  return (
    <div ref={boxRef} className="absolute inset-0 overflow-hidden">
      <picture>
        <source media="(min-width: 768px)" srcSet={wideProps.srcSet} sizes={wideProps.sizes} />
        <img {...tallProps} srcSet={tallSrcSet} className={`absolute inset-0 h-full w-full ${FIT}`} alt={ALT} />
      </picture>
      {allowed && (
        <video
          ref={videoRef}
          className={`absolute inset-0 h-full w-full ${FIT} transition-opacity duration-700 ${frames ? 'opacity-100' : 'opacity-0'}`}
          muted
          playsInline
          preload="none"
          aria-hidden="true"
          tabIndex={-1}
          onPlaying={() => {
            setFrames(true);
            setPlayback('playing');
          }}
          onPause={() => setPlayback((p) => (p === 'ended' ? p : 'paused'))}
          onEnded={() => setPlayback('ended')}
          onError={() => {
            if (videoRef.current?.getAttribute('src')) {
              setFailed(true);
              setFrames(false);
            }
          }}
        />
      )}
      {allowed && (
        <button
          type="button"
          onClick={control}
          className="absolute bottom-[4.25rem] right-3 z-20 inline-flex h-11 min-w-11 items-center justify-center gap-2 rounded-full bg-paper/80 px-3 text-xs font-medium text-ink backdrop-blur hover:bg-paper lg:bottom-auto lg:right-5 lg:top-[calc(var(--header-h,0px)+12px)]"
        >
          {playback === 'playing' ? (
            <svg width="12" height="12" viewBox="0 0 12 12" aria-hidden>
              <rect x="2" y="1.5" width="2.6" height="9" rx="0.8" fill="currentColor" />
              <rect x="7.4" y="1.5" width="2.6" height="9" rx="0.8" fill="currentColor" />
            </svg>
          ) : playback === 'ended' ? (
            <svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" aria-hidden>
              <path d="M3.5 12a8.5 8.5 0 1 0 2.5-6M3.5 3.5V8H8" />
            </svg>
          ) : (
            <svg width="12" height="12" viewBox="0 0 12 12" aria-hidden>
              <path d="M3 1.8v8.4c0 .5.5.8.9.5l6.3-4.2a.6.6 0 0 0 0-1L3.9 1.3c-.4-.3-.9 0-.9.5Z" fill="currentColor" />
            </svg>
          )}
          <span className="sr-only sm:not-sr-only">{label}</span>
        </button>
      )}
    </div>
  );
}
